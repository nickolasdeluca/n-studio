  C_VC_UTF8       VARCHAR(100) CHARACTER SET UTF8,
  C_VC_NONE       VARCHAR(100) CHARACTER SET NONE,
  C_BLOB_TEXT     BLOB SUB_TYPE TEXT,
  C_BLOB_BIN      BLOB SUB_TYPE 0,
