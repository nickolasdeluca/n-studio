CREATE VIEW V_TIPOS AS
  SELECT ID, C_VARCHAR, C_NUMERIC_18_4 FROM TIPOS;

/* Bulk table for the streaming / grid-perf spike. */
CREATE TABLE BULK_ROWS (
  ID         INTEGER NOT NULL,
  NOME       VARCHAR(120),
  VALOR      NUMERIC(15,2),
  CRIADO_EM  TIMESTAMP,
  CONSTRAINT PK_BULK_ROWS PRIMARY KEY (ID)
);

CREATE INDEX IDX_BULK_NOME ON BULK_ROWS (NOME);

/* What the object viewers read: keys of every kind, a check, a computed
   column, defaults, comments, and indices that are not plain. */
CREATE TABLE PEDIDO (
  ID       D_ID,
  CLIENTE  VARCHAR(60) NOT NULL,
  EMISSAO  DATE DEFAULT CURRENT_DATE NOT NULL,
  CONSTRAINT PK_PEDIDO PRIMARY KEY (ID),
  CONSTRAINT UQ_PEDIDO UNIQUE (CLIENTE, EMISSAO)
);

CREATE TABLE PEDIDO_ITEM (
  PEDIDO  D_ID,
  ITEM    SMALLINT NOT NULL,
  QTD     NUMERIC(9,3) DEFAULT 1 NOT NULL,
  PRECO   D_MONEY,
  TOTAL   COMPUTED BY (QTD * PRECO),
  PAGO    D_FLAG,
  CONSTRAINT PK_PEDIDO_ITEM PRIMARY KEY (PEDIDO, ITEM),
  CONSTRAINT FK_ITEM_PEDIDO FOREIGN KEY (PEDIDO) REFERENCES PEDIDO (ID) ON DELETE CASCADE,
  CONSTRAINT CK_ITEM_QTD CHECK (QTD > 0)
);

CREATE DESCENDING INDEX IDX_ITEM_PRECO ON PEDIDO_ITEM (PRECO);
CREATE INDEX IDX_PEDIDO_CLIENTE ON PEDIDO COMPUTED BY (UPPER(CLIENTE));

COMMENT ON TABLE PEDIDO IS 'Orders';
COMMENT ON COLUMN PEDIDO.CLIENTE IS 'Who it''s for';

CREATE VIEW V_PEDIDO_TOTAL (PEDIDO, TOTAL) AS
  SELECT I.PEDIDO, SUM(I.TOTAL) FROM PEDIDO_ITEM I GROUP BY I.PEDIDO;

SET TERM ^ ;

CREATE PROCEDURE P_FIXTURE (P_N INTEGER)
RETURNS (R_ID INTEGER, R_TXT VARCHAR(100))
AS
BEGIN
  R_ID = P_N;
  R_TXT = 'proc row ' || P_N;
  SUSPEND;
END^

CREATE TRIGGER TIPOS_BI FOR TIPOS ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = GEN_ID(GEN_TIPOS_ID, 1);
END^

/* Parameters declared every way there is, and something to depend on. */
CREATE PROCEDURE P_PEDIDO_TOTAL (
  P_PEDIDO TYPE OF D_ID,
  P_MINIMO NUMERIC(18,4) = 0)
RETURNS (R_TOTAL TYPE OF COLUMN PEDIDO_ITEM.PRECO)
AS
BEGIN
  SELECT V.TOTAL FROM V_PEDIDO_TOTAL V WHERE V.PEDIDO = :P_PEDIDO INTO :R_TOTAL;
  IF (R_TOTAL < P_MINIMO) THEN
    EXCEPTION E_FIXTURE;
  SUSPEND;
END^

/* Bulk table for the streaming / grid-perf spike: 1,000,000 rows. */
CREATE PROCEDURE P_SEED_BULK (P_ROWS INTEGER)
AS
DECLARE VARIABLE I INTEGER;
BEGIN
  I = 0;
  WHILE (I < P_ROWS) DO
  BEGIN
    INSERT INTO BULK_ROWS (ID, NOME, VALOR, CRIADO_EM)
    VALUES (:I, 'PRODUTO COMPLEMENTO ' || :I, MOD(:I, 100000) / 100.0,
            DATEADD(:I SECOND TO TIMESTAMP '2020-01-01 00:00:00'));
    I = I + 1;
  END
END^

SET TERM ; ^

/* Privileges: a role, a user (which need not exist to be granted to), a
   procedure and PUBLIC, on objects whose DDL no test spells out in full. */
CREATE ROLE R_FIXTURE;

GRANT SELECT, UPDATE (NOME, VALOR) ON BULK_ROWS TO ROLE R_FIXTURE;
GRANT ALL ON BULK_ROWS TO U_FIXTURE WITH GRANT OPTION;
GRANT SELECT ON BULK_ROWS TO PROCEDURE P_FIXTURE;
GRANT SELECT ON V_TIPOS TO PUBLIC;
GRANT EXECUTE ON PROCEDURE P_SEED_BULK TO U_FIXTURE;
GRANT R_FIXTURE TO U_FIXTURE WITH ADMIN OPTION;

COMMIT;
